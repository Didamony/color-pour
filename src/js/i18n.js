  let lang = 'en';

  function t(key, vars) {
    let s = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
    return s;
  }

  function setLang(l) {
    lang = dict[l] ? l : 'en';
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    apply(document);
  }

  function apply(rootEl) {
    rootEl.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    rootEl.querySelectorAll('[data-i18n-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nLabel)); });
  }

  function guess() {
    const l = (navigator.language || 'en').toLowerCase();
    return l.startsWith('ar') ? 'ar' : 'en';
  }

  CP.I18n = { t, setLang, apply, guess, get lang() { return lang; } };
